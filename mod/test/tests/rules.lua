-- Rules read from the mod's source, and checks over the whole run: only the game thread runs Lua, every
-- config.txt key is kept, slot data is read only by listed keys the APWorld sends, every LoadAsset path is full.

group("Lua runs only on the game thread", function()
    -- A LoopAsync or key-bind callback runs on another thread over the same Lua state, so it only reads a flag and
    -- hands a function made beforehand to ExecuteInGameThread. ExecuteWithDelay's callback runs off the game thread
    -- too, so it is never used. The loop shape this check reads, one statement per line:
    --     LoopAsync(<ms or UPDATE_MS>, function()
    --         ExecuteInGameThread(<name>)        (or: if <flag> then ExecuteInGameThread(<name>) end, return false)
    --     end)
    local UPDATE_MS = require("util").UPDATE_MS
    local FASTEST_LOOP_MS = 300          -- LoopAsync is only safe at 300 ms or slower (docs/style-guide.md, Lua)
    local bad, loops = {}, 0
    local function checkLoopBody(f, lines, k, ind)
        local j = k + 1
        while lines[j] and lines[j] ~= ind .. "end)" do
            local body = lines[j]:gsub("^%s+", "")
            local ok = body:match("^ExecuteInGameThread%([%w_.]+%)$")
                or body:match("^if [%w_.]+ then ExecuteInGameThread%([%w_.]+%) end$")
                or body == "return false" or body:match("^%-%-")
            if not ok then
                bad[#bad + 1] = f .. ":" .. j .. ": " .. body
            end
            j = j + 1
        end
    end
    local function checkLine(f, lines, k)
        local line = lines[k]
        local code = line:gsub("%-%-.*$", "")
        if code:find("ExecuteWithDelay%(") then
            bad[#bad + 1] = f .. ":" .. k .. ": ExecuteWithDelay (off-thread)"
        end
        if code:find("RegisterKeyBind%(") and not code:find("function%(%) ExecuteInGameThread%([%w_.]+%) end%)") then
            bad[#bad + 1] = f .. ":" .. k .. ": a key bind that does more than hand over a function made beforehand"
        end
        if not code:find("LoopAsync%(") then return end
        local ind, every = line:match("^(%s*)LoopAsync%(([%w_.]+), function%(%)%s*$")
        local ms = every and (tonumber(every) or (every:match("UPDATE_MS$") and UPDATE_MS))
        if not ms then
            bad[#bad + 1] = f .. ":" .. k .. ": a LoopAsync this check cannot read"
            return
        end
        loops = loops + 1
        if ms < FASTEST_LOOP_MS then
            bad[#bad + 1] = f .. ":" .. k .. ": a " .. ms .. " ms loop (faster than 300 ms corrupts Lua's state)"
        end
        checkLoopBody(f, lines, k, ind)
    end
    local ls = io.popen('ls "' .. MOD .. '/Scripts"')
    for f in ls:lines() do
        local fh = f:match("%.lua$") and io.open(MOD .. "/Scripts/" .. f)
        local src = fh and fh:read("a") or ""
        if fh then
            fh:close()
        end
        if not src:find("^%-%- Generated by") then
            local lines = {}
            for line in (src .. "\n"):gmatch("(.-)\n") do
                lines[#lines + 1] = line
            end
            for k = 1, #lines do
                checkLine(f, lines, k)
            end
        end
    end
    ls:close()
    local slow = true
    for _, ms in ipairs(loopIntervals) do
        slow = slow and ms >= FASTEST_LOOP_MS
    end
    expect(loops >= 1 and slow and #bad == 0, "every LoopAsync and key bind callback only hands over a function made"
        .. " beforehand, no loop is faster than 300 ms, and nothing calls ExecuteWithDelay: " .. loops .. " loop(s); "
        .. table.concat(bad, " | "))
end)

group("every config.txt key the mod reads is kept when the title menu rewrites the file", function()
    -- Every config.txt key the mod reads is one the title menu keeps when it rewrites the file (CONFIG_KEYS).
    local fh = io.open(MOD .. "/Scripts/config.lua")
    local src = fh and fh:read("a") or ""
    if fh then
        fh:close()
    end
    local listed = {}
    for key in (src:match("local CONFIG_KEYS = (%b{})") or ""):gmatch('"([%w_]+)"') do
        listed[key] = true
    end
    local missing, seen = {}, {}
    local ls = io.popen('ls "' .. MOD .. '/Scripts"')
    for name in ls:lines() do
        local h = name:match("%.lua$") and io.open(MOD .. "/Scripts/" .. name)
        local text = h and h:read("a") or ""
        if h then
            h:close()
        end
        for key in text:gmatch("cfg%.([%w_]+)") do
            if not listed[key] and not seen[key] then
                seen[key] = true
                missing[#missing + 1] = name .. ": " .. key
            end
        end
    end
    ls:close()
    expect(next(listed) ~= nil and #missing == 0,
           "every config.txt key the mod reads is kept when the title menu rewrites the file: "
           .. table.concat(missing, ", "))
end)

group("slot data", function()
    -- The mod reads slot data only through slot_data.lua, and only keys listed in its SLOT.KEYS; each listed key is
    -- one the APWorld sends. The APWorld's side, read from its source (this runs from the repository's top folder):
    --     SLOT_DATA_OPTIONS = ( "goal", "tower_count", ... )     the options sent as options.<name>
    --     def fill_slot_data(self) ... return {"options": ..., "relics": ..., ...}   the top-level keys
    local SLOT = require("slot_data")
    local function readFile(path)
        local fh = io.open(path)
        local text = fh and fh:read("a") or ""
        if fh then
            fh:close()
        end
        return text
    end
    local function luaFiles()
        local names, ls = {}, io.popen('ls "' .. MOD .. '/Scripts"')
        for name in ls:lines() do
            if name:match("%.lua$") then
                names[#names + 1] = name
            end
        end
        ls:close()
        return names
    end

    -- No other file calls AP_SlotData, and every key the code names is listed.
    local direct, unlisted = {}, {}
    for _, name in ipairs(luaFiles()) do
        local text = readFile(MOD .. "/Scripts/" .. name)
        if name ~= "slot_data.lua" and not text:find("^%-%- Generated by") then
            local lineNo = 0
            for line in (text .. "\n"):gmatch("(.-)\n") do
                lineNo = lineNo + 1
                local code = line:gsub("%-%-.*$", "")
                if code:find("AP_SlotData") then
                    direct[#direct + 1] = name .. ":" .. lineNo
                end
                for key in code:gmatch('SLOT%.%a+%("([%w_.]+)"%s*[,)]') do
                    if not SLOT.KEYS[key] then
                        unlisted[#unlisted + 1] = name .. ":" .. lineNo .. " " .. key
                    end
                end
            end
        end
    end
    expect(#direct == 0, "only slot_data.lua calls AP_SlotData: " .. table.concat(direct, ", "))
    expect(#unlisted == 0, "every slot data key the mod names is in SLOT.KEYS: " .. table.concat(unlisted, ", "))

    -- The keys built by joining text are listed too: the crate weights and Speed Boost's multipliers.
    local built = {}
    for _, option in pairs(require("crates").WEIGHT_KEYS) do
        built[#built + 1] = "options." .. option
    end
    for _, f in ipairs(require("run_style").FIELDS) do
        built[#built + 1] = "options." .. f.option
    end
    local builtMissing = {}
    for _, key in ipairs(built) do
        if not SLOT.KEYS[key] then
            builtMissing[#builtMissing + 1] = key
        end
    end
    expect(#builtMissing == 0, "every slot data key the mod builds is in SLOT.KEYS: " .. table.concat(builtMissing, ", "))

    -- Every listed key (but the old names) is one the APWorld sends.
    local sentOptions, sentTop = {}, {}
    local pyFiles = io.popen("ls apworld/palworld/*.py")
    for path in pyFiles:lines() do
        local text = readFile(path)
        for name in (text:match("SLOT_DATA_OPTIONS = (%b())") or ""):gmatch('"([%w_]+)"') do
            sentOptions[name] = true
        end
        local body = text:match("def fill_slot_data%(self%).-return (%b{})")
        for name in (body or ""):gmatch('"([%w_]+)":') do
            sentTop[name] = true
        end
    end
    pyFiles:close()
    expect(next(sentOptions) ~= nil and sentTop.options,
           "the APWorld's SLOT_DATA_OPTIONS and fill_slot_data were found in apworld/palworld/*.py")
    local notSent = {}
    for key, entry in pairs(SLOT.KEYS) do
        local option = key:match("^options%.(.+)$")
        local sent = (option and sentOptions[option]) or (not option and sentTop[key])
        if not sent and not entry.old then
            notSent[#notSent + 1] = key
        end
    end
    table.sort(notSent)
    expect(#notSent == 0, "every key in SLOT.KEYS is one the APWorld sends: " .. table.concat(notSent, ", "))

    -- A key not listed is refused, not read.
    local ok, err = pcall(SLOT.text, "options.not_an_option")
    expect(not ok and tostring(err):find("not listed"), "SLOT.text refuses a key not in SLOT.KEYS: " .. tostring(err))
end)

group("the whole run", function()
    expect(#badLoads == 0, "every LoadAsset path is a full /Game/Dir/Asset.Asset: " .. table.concat(badLoads, ", "))
    expect(not logged("but the bag and equipment slots gained"),
           "the bag and equipment slots gained what the game said it took")
end)
