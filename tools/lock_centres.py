"""Writes mod/PalworldArchipelago/Scripts/region_centres.lua: for each lock of region_labels.png (one lock index per
pixel), the point deepest inside it (largest distance to its edge), and the point nearest the starting lock that is
still a whole stamp inside it, both as 0-1 map coordinates, and how far the stamp's point is from the lock's edge.
The map stamp for a closed lock is drawn at the second (at the deepest point it sat under the map's fog of war, which
a closed lock never clears; the side facing home is the side players walk up to), or the first when the lock is too
thin for a stamp.
    python tools/lock_centres.py      (needs numpy, scipy, pillow)
    LOCK_SIZE=areas python tools/lock_centres.py   (the 75 areas: area_labels.png -> area_centres.lua)
Tests: none of its own; the Lua harness loads its file with the mod (locks.lua, map_picture.lua).
"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt

from lock_groups import PREFIX

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "mod" / "PalworldArchipelago"
START = 1                        # Windswept Island, first in both sets (0 = Open sea)
MAP_PX = 4096                    # the map picture's size the stamp is measured on
# The room a stamp needs, in pixels of the 4096 map: half of map_picture.lua's STAMP_PX (88), plus 12 to spare.
STAMP_INSET_PX = 56


def centre_of(labels, k, from_start, inset):
    """Lock k's deepest point and its stamp's point (row, col, each), with that point's room (pixels of the 4096 map)
    and the deepest point's depth; None when the picture has no pixel of k."""
    inside = np.pad(labels == k, 1)                    # padded so the image edge counts as an edge
    if not inside.any():
        return None
    depth = distance_transform_edt(inside)[1:-1, 1:-1]
    deepest = np.unravel_index(np.argmax(depth), depth.shape)
    room = depth >= inset
    if room.any():
        stamp = np.unravel_index(np.argmin(np.where(room, from_start, np.inf)), depth.shape)
    else:
        stamp = deepest
    return deepest, stamp, depth[stamp] * MAP_PX / labels.shape[0], depth[deepest]


def centre_line(k, centre, from_start, n):
    """Lock k's row of the file: { u, v, nu, nv, room } with how deep and how far from the start, as a comment."""
    (r, c), (nr, nc), room_px, deepest_depth = centre
    return (f"    [{k}] = {{ {(c + 0.5) / n:.4f}, {(r + 0.5) / n:.4f}, {(nc + 0.5) / n:.4f}, {(nr + 0.5) / n:.4f}, "
            f"{room_px:.0f} }},   -- {deepest_depth * 1.0:.0f} px deep; {from_start[nr, nc]:.0f} px from the start")


def main():
    labels = np.array(Image.open(MOD / f"{PREFIX}_labels.png"))
    n = labels.shape[0]
    from_start = distance_transform_edt(labels != START)
    lines = [f"-- Generated by tools/lock_centres.py from {PREFIX}_labels.png; do not edit by hand.",
             "-- lock index -> { u, v, nu, nv, room }: the point deepest inside the lock, and the point nearest the",
             "-- starting lock with a whole stamp inside it (the stamp goes there), 0-1 across and down the map; room: "
             "how",
             "-- far that point is from the lock's edge, in pixels of the 4096 map (walls.lua shrinks the stamp of a "
             "lock",
             "-- too small for it).",
             "return {"]
    for k in range(1, int(labels.max()) + 1):
        centre = centre_of(labels, k, from_start, STAMP_INSET_PX * n / MAP_PX)
        if centre:
            lines.append(centre_line(k, centre, from_start, n))
    lines.append("}")
    (MOD / "Scripts" / f"{PREFIX}_centres.lua").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
