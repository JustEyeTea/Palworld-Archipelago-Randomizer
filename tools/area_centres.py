"""Writes mod/PalworldArchipelago/Scripts/area_centres.lua: for each area of area_labels.png (one area index per
pixel), the point deepest inside it (largest distance to its edge), as 0-1 map coordinates. The map stamp for a locked
area is drawn there, so it never sits on a border.
    python tools/area_centres.py      (needs numpy, scipy, pillow)"""
from pathlib import Path

import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / 'mod' / 'PalworldArchipelago'
labels = np.array(Image.open(MOD / 'area_labels.png'))
n = labels.shape[0]
lines = ['-- Generated by tools/area_centres.py from area_labels.png; do not edit by hand.',
         '-- area index -> { u, v }: the point deepest inside the area, 0-1 across and down the map.', 'return {']
for k in range(1, int(labels.max()) + 1):
    inside = np.pad(labels == k, 1)                  # padded so the image edge counts as an edge
    if not inside.any():
        continue
    depth = distance_transform_edt(inside)[1:-1, 1:-1]
    r, c = np.unravel_index(np.argmax(depth), depth.shape)
    lines.append(f'    [{k}] = {{ {(c + 0.5) / n:.4f}, {(r + 0.5) / n:.4f} }},   -- {depth[r, c] * 1.0:.0f} px from its edge')
lines.append('}')
(MOD / 'Scripts' / 'area_centres.lua').write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
