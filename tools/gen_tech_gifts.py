"""Writes mod/PalworldArchipelago/Scripts/tech_gifts.lua: what each technology makes, for Run Style "Sync (Nomad)",
where a received tech also hands over its product. Gear (one of each) goes to the bag; stackables come as a stack.
Techs that only unlock buildings have no entry: a building can't be handed over. Reads the private table dumps.
    python3 tools/gen_tech_gifts.py <tables dir> <all-tables dir>
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'mod' / 'PalworldArchipelago' / 'Scripts' / 'tech_gifts.lua'
rd = lambda p: list(csv.DictReader(open(p, encoding='utf-8'), delimiter='\t'))
tables, all_tables = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])

# FNames ignore case (a tech names recipe Bow_triple; the item row is Bow_Triple), so look up lower-case.
items = {r['row'].lower(): r for r in rd(all_tables / 'DT_ItemDataTable.tsv')}
recipes = {r['row'].lower(): r for r in rd(all_tables / 'DT_ItemRecipeDataTable.tsv')}

# Kept in the player's own slots (equipment and key items), never a chest: one each, to the bag.
GEAR = {'Weapon', 'Armor', 'Accessory', 'Glider', 'Essential', 'CaptureItemModifier'}
# A stack of the rest, by the item's TypeB (enough to use for a while; more needs the recipe, which unlocks too).
STACK = {'SPWeaponCaptureBall': 10, 'ConsumeBullet': 50, 'WeaponThrowObject': 5, 'ConsumeFishingBait': 10}
STACK_BY_A = {'Material': 10, 'Food': 5, 'Consume': 3}
NOT_GEAR_B = {'WeaponThrowObject'}                    # grenades are weapons that stack


def tail(v):
    return (v or '').split('::')[-1]


gifts, unknown = {}, []
for r in rd(tables / 'DT_TechnologyRecipeUnlock.tsv'):
    out = []
    for rid in re.findall(r'[A-Za-z0-9_]+', r['UnlockItemRecipes'] or ''):
        if rid == 'None':
            continue
        pid = recipes[rid.lower()]['Product_Id'] if rid.lower() in recipes else rid
        it = items.get(pid.lower())
        if not it:
            unknown.append(f"{r['row']}:{pid}")
            continue
        a, b = tail(it['TypeA']), tail(it['TypeB'])
        if a in GEAR and b not in NOT_GEAR_B:
            out.append((it['row'], 1, True))
        else:
            n = STACK.get(b) or STACK_BY_A.get(a) or 5
            n = min(n, int(it['MaxStackCount'] or n) or n)
            out.append((it['row'], n, False))
    if out:
        gifts[r['row']] = out

lines = ['-- Generated by tools/gen_tech_gifts.py from the game\'s tables; do not edit by hand.',
         '-- tech id -> { { item id, count, bag = true for gear } }: what Run Style "Sync (Nomad)" hands over with it.',
         'return {']
for t, out in sorted(gifts.items()):
    parts = ', '.join(f'{{ "{i}", {n}{", bag = true" if g else ""} }}' for i, n, g in out)
    lines.append(f'    ["{t}"] = {{ {parts} }},')
lines += ['}', '']
OUT.write_text('\n'.join(lines))
print(f'wrote {OUT.relative_to(ROOT)}: {len(gifts)} techs with gifts; products not in the item table: {unknown}')
