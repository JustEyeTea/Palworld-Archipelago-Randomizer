"""Writes mod/PalworldArchipelago/Scripts/tech_gifts.lua: what each technology makes, for Run Style "Nomad",
where a received tech also hands over its product. Gear comes one of each; stackables come as a stack.
Techs that only unlock buildings have no entry: a building can't be handed over. Reads the private table dumps.
    python3 tools/gen_tech_gifts.py <tables dir> <all-tables dir>
Tests: none of its own; the Lua harness loads its file with the mod (sync.lua), and tests/crates_run_style.lua
tests Nomad with it.
"""
import pathlib
import re
import sys

from table_dumps import read_table

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "mod" / "PalworldArchipelago" / "Scripts" / "tech_gifts.lua"

# Kept in the player's own slots (equipment and key items): one each, marked gear for the mailbox's gear list.
GEAR = {"Weapon", "Armor", "Accessory", "Glider", "Essential", "CaptureItemModifier"}
# A stack of the rest, by the item's TypeB (enough to use for a while; more needs the recipe, which unlocks too).
STACK = {"SPWeaponCaptureBall": 10, "ConsumeBullet": 50, "WeaponThrowObject": 5, "ConsumeFishingBait": 10}
STACK_BY_A = {"Material": 10, "Food": 5, "Consume": 3}
STACK_OTHERWISE = 5                                   # an item of a type neither table names
NOT_GEAR_B = {"WeaponThrowObject"}                    # grenades are weapons that stack


def type_name(value):
    """The last part of an enum value as the dump writes it ("EPalItemTypeA::Weapon" -> "Weapon")."""
    return (value or "").split("::")[-1]


def gift_of(item):
    """What a tech hands over of one item: (item id, how many, whether it is gear)."""
    type_a, type_b = type_name(item["TypeA"]), type_name(item["TypeB"])
    if type_a in GEAR and type_b not in NOT_GEAR_B:
        return item["row"], 1, True
    count = STACK.get(type_b) or STACK_BY_A.get(type_a) or STACK_OTHERWISE
    return item["row"], min(count, int(item["MaxStackCount"] or count) or count), False


def tech_gifts(tables, all_tables):
    """Tech id -> its gifts, and the products the item table lacks ("tech:product")."""
    # FNames ignore case (a tech names recipe Bow_triple; the item row is Bow_Triple), so look up lower-case.
    items = {row["row"].lower(): row for row in read_table(all_tables, "DT_ItemDataTable.tsv")}
    recipes = {row["row"].lower(): row for row in read_table(all_tables, "DT_ItemRecipeDataTable.tsv")}
    gifts, unknown = {}, []
    for tech in read_table(tables, "DT_TechnologyRecipeUnlock.tsv"):
        made = []
        for recipe in re.findall(r"[A-Za-z0-9_]+", tech["UnlockItemRecipes"] or ""):
            if recipe == "None":
                continue
            product = recipes[recipe.lower()]["Product_Id"] if recipe.lower() in recipes else recipe
            if product.lower() in items:
                made.append(gift_of(items[product.lower()]))
            else:
                unknown.append(f"{tech['row']}:{product}")
        if made:
            gifts[tech["row"]] = made
    return gifts, unknown


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    gifts, unknown = tech_gifts(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
    lines = ["-- Generated by tools/gen_tech_gifts.py from the game's tables; do not edit by hand.",
             '-- tech id -> { { id = item id, n = count, gear = true for gear } }: what Run Style "Nomad" hands over '
             "with it.",
             "return {"]
    for tech, made in sorted(gifts.items()):
        parts = ", ".join(f'{{ id = "{item}", n = {count}{", gear = true" if gear else ""} }}'
                          for item, count, gear in made)
        lines.append(f'    ["{tech}"] = {{ {parts} }},')
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(gifts)} techs with gifts; products not in the item table: {unknown}")


if __name__ == "__main__":
    main()
