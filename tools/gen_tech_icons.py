"""Writes mod/PalworldArchipelago/Scripts/tech_icons.lua: each technology's icon texture (an asset path inside the game)
and whether it unlocks buildings, so a shop slot holding one of your own techs can show that tech's icon and its card
category ("Structures" or "Items"). Reads the private table dumps.
    python3 tools/gen_tech_icons.py <tables dir> <all-tables dir>
"""
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'mod' / 'PalworldArchipelago' / 'Scripts' / 'tech_icons.lua'
rd = lambda p: list(csv.DictReader(open(p), delimiter='\t'))
tables, all_tables = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])

# A tech's IconName is a building icon row or an item icon row (buildings first, as the game's own cards show them).
build = {r['row'].lower(): r['SoftIcon'] for r in rd(all_tables / 'DT_BuildObjectIconDataTable.tsv')}
item = {r['row'].lower(): r['Icon'] for r in rd(all_tables / 'DT_ItemIconDataTable.tsv')}
icons, missing, structures = {}, [], []
for r in rd(tables / 'DT_TechnologyRecipeUnlock.tsv'):
    if r['UnlockBuildObjects'].strip():
        structures.append(r['row'])
    key = r['IconName'].lower()
    path = next((p for p in (build.get(key), item.get(key)) if p and p != 'None'), None)
    if path:
        icons[r['row']] = path
    else:
        missing.append(r['row'])
lines = ['-- Generated by tools/gen_tech_icons.py from the game\'s tables; do not edit by hand.', 'return {',
         '    -- tech id -> icon texture asset path', '    icons = {']
lines += [f'        ["{t}"] = "{p}",' for t, p in sorted(icons.items())]
lines += ['    },', '    -- techs that unlock buildings (their cards say "Structures"; the others "Items")', '    structures = {']
lines += [f'        ["{t}"] = true,' for t in sorted(structures)]
lines += ['    },', '}', '']
OUT.write_text('\n'.join(lines))
print(f'wrote {OUT.relative_to(ROOT)}: {len(icons)} icons, missing {missing}')
