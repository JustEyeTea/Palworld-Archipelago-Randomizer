"""Writes mod/PalworldArchipelago/Scripts/tech_icons.lua: each technology's icon texture (an asset path inside the game)
and whether it unlocks buildings, so a shop slot holding one of your own techs can show that tech's icon and its card
category ("Structures" or "Items"). Reads the private table dumps.
    python3 tools/gen_tech_icons.py <tables dir> <all-tables dir>
Tests: none of its own; the Lua harness loads its file with the mod (shop_cards.lua).
"""
import pathlib
import sys

from table_dumps import read_table

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "mod" / "PalworldArchipelago" / "Scripts" / "tech_icons.lua"


def tech_icons(tables, all_tables):
    """(tech id -> icon path, the techs with no icon, the techs that unlock buildings). A tech's IconName is a
    building icon row or an item icon row (buildings first, as the game's own cards show them)."""
    building_icons = {row["row"].lower(): row["SoftIcon"]
                      for row in read_table(all_tables, "DT_BuildObjectIconDataTable.tsv")}
    item_icons = {row["row"].lower(): row["Icon"] for row in read_table(all_tables, "DT_ItemIconDataTable.tsv")}
    icons, missing, structures = {}, [], []
    for tech in read_table(tables, "DT_TechnologyRecipeUnlock.tsv"):
        if tech["UnlockBuildObjects"].strip():
            structures.append(tech["row"])
        key = tech["IconName"].lower()
        path = next((p for p in (building_icons.get(key), item_icons.get(key)) if p and p != "None"), None)
        if path:
            icons[tech["row"]] = path
        else:
            missing.append(tech["row"])
    return icons, missing, structures


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    icons, missing, structures = tech_icons(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
    lines = ["-- Generated by tools/gen_tech_icons.py from the game's tables; do not edit by hand.", "return {",
             "    -- tech id -> icon texture asset path", "    icons = {"]
    lines += [f'        ["{tech}"] = "{path}",' for tech, path in sorted(icons.items())]
    lines += ["    },", '    -- techs that unlock buildings (their cards say "Structures"; the others "Items")',
              "    structures = {"]
    lines += [f'        ["{tech}"] = true,' for tech in sorted(structures)]
    lines += ["    },", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(icons)} icons, missing {missing}")


if __name__ == "__main__":
    main()
