"""Writes mod/PalworldArchipelago/Scripts/wall_region_variants.lua: which version of its region's wall each of the 75
areas wears (Lock Size: areas). Every region's wall comes in several versions (logicmod/art/walls); two areas of one
region that touch (share a wall piece in area_walls.lua) get different versions, so the wall between them shows a
change, and each region's versions are used about equally. Reads only the repository's own area_walls.lua and
area_regions.lua: no game files.
    python3 tools/wall_region_variants.py
Tests: none of its own; the Lua harness's tests/locks_hud.lua checks every area is in the file with its region.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "mod" / "PalworldArchipelago" / "Scripts"
WALLS_LUA = SCRIPTS / "area_walls.lua"
AREA_REGIONS_LUA = SCRIPTS / "area_regions.lua"
OUT = SCRIPTS / "wall_region_variants.lua"
WALL_ART = ROOT / "logicmod" / "art" / "walls"
# The versions each region's wall has: logicmod/art/walls/ap-wall-region-<region>-0.png to -3.png.
WALL_VERSIONS = 4
OPEN_SEA = 0                    # area_walls.lua's lock 0: open sea, never an area

HEADER = [
    "-- Generated by tools/wall_region_variants.py from area_regions.lua and area_walls.lua; do",
    "-- not edit by hand. Lock Size: areas: each area's region wall and version, keyed by area name.",
    "-- Two touching areas of one region never share a version.",
    "-- Texture: ap-wall-region-<region>-<version>.png; Back = the region colour.",
]


def slug(name):
    """A region's name as its wall art's file names spell it: "Sea Breeze Archipelago" -> "sea-breeze-archipelago"."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def area_names(walls_lua):
    """area_walls.lua's locks list, by lock index: index 0 is open sea, 1 to 75 the areas."""
    return re.findall(r'"([^"]+)"', walls_lua.split("locks =")[1].split("}")[0])


def region_of_area(regions_lua):
    """area_regions.lua as {area name: region name}."""
    return dict(re.findall(r'\["(.+?)"\] = "(.+?)"', regions_lua))


def touching_areas(walls_lua, lock_count):
    """For each area index, the area indexes it shares a wall piece with (open sea left out)."""
    near = {area: set() for area in range(1, lock_count)}
    for side_a, side_b in re.findall(r"lockA = (\d+), lockB = (\d+)", walls_lua):
        side_a, side_b = int(side_a), int(side_b)
        if OPEN_SEA not in (side_a, side_b) and side_a != side_b:
            near[side_a].add(side_b)
            near[side_b].add(side_a)
    return near


def versions_taken(area, near, region, version):
    """The versions already given to the areas that touch `area` and share its region."""
    return {version[other] for other in near[area] if other in version and region[other] == region[area]}


def most_constrained(waiting, near, region, version):
    """The next area to give a version: the one with the most versions taken round it, then the most neighbours in
    its region, then the lowest index."""
    def constraint(area):
        same_region_neighbours = sum(region[other] == region[area] for other in near[area])
        return len(versions_taken(area, near, region, version)), same_region_neighbours, -area
    return max(waiting, key=constraint)


def pick_versions(region, near):
    """{area index: version}: in each region, the most constrained area takes the least-used version no touching area
    of its region has yet (any version if all are taken)."""
    version = {}
    for each_region in sorted(set(region.values())):
        areas = [area for area in region if region[area] == each_region]
        used = [0] * WALL_VERSIONS
        waiting = list(areas)
        while waiting:
            area = most_constrained(waiting, near, region, version)
            taken = versions_taken(area, near, region, version)
            free = [v for v in range(WALL_VERSIONS) if v not in taken] or list(range(WALL_VERSIONS))
            chosen = min(free, key=lambda v: (used[v], v))
            version[area] = chosen
            used[chosen] += 1
            waiting.remove(area)
    return version


def check_wall_art(region_slugs):
    """Stops if a version the file will name has no wall picture in logicmod/art/walls."""
    missing = [f"ap-wall-region-{name}-{v}.png" for name in sorted(region_slugs) for v in range(WALL_VERSIONS)
               if not (WALL_ART / f"ap-wall-region-{name}-{v}.png").exists()]
    if missing:
        sys.exit(f"no wall art in {WALL_ART} for: {', '.join(missing)}")


def lua_string(text):
    """A Lua string literal of `text`."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    walls_lua = WALLS_LUA.read_text(encoding="utf-8")
    names = area_names(walls_lua)
    regions = region_of_area(AREA_REGIONS_LUA.read_text(encoding="utf-8"))
    region = {area: slug(regions[names[area]]) for area in range(1, len(names))}
    check_wall_art(set(region.values()))
    version = pick_versions(region, touching_areas(walls_lua, len(names)))
    lines = HEADER + ["return {"]
    for area in sorted(region):
        lines.append(f'    [{lua_string(names[area])}] = {{ region = "{region[area]}", version = {version[area]} }},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(region)} areas")


if __name__ == "__main__":
    main()
