"""Writes apworld/palworld/test/frozen_ids.tsv, the item and location ids test_ids.py holds the APWorld to, from the
APWorld's own tables (apworld/palworld/data.py).
    python3 tools/freeze_ids.py
Run it only after a change that keeps every id and changes names on purpose (a rename), or to freeze the ids a game
update added. It stops, writing nothing, if a name now has another id or an id of the file it replaces is gone; a
rename (the same kind and id under a new name) is allowed, so read `git diff apworld/palworld/test/frozen_ids.tsv`
to check each renamed line is meant.
Tests: none of its own; test_ids.py holds the APWorld to the file it writes.
"""
import pathlib
import sys

from apworld_loader import load_world_tables

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "apworld" / "palworld" / "test" / "frozen_ids.tsv"
HEADER = ("# Generated by tools/freeze_ids.py from apworld/palworld/data.py; do not edit by hand.\n"
          "# kind<TAB>offset<TAB>name, where the id is data.BASE + offset: every id test_ids.py holds still.\n")


def read_frozen(text):
    """The frozen lines of a file's text: {(kind, name): offset}."""
    frozen = {}
    for line in text.splitlines():
        if line and not line.startswith("#"):
            kind, offset, name = line.split("\t", 2)
            frozen[(kind, name)] = int(offset)
    return frozen


def moved_ids(old_text, new_text):
    """What the new lines would break of the old ones: a name now at another offset, or an offset no name holds."""
    old, new = read_frozen(old_text), read_frozen(new_text)
    problems = [f"{kind} {name!r}: id offset {offset} would become {new[(kind, name)]}"
                for (kind, name), offset in old.items() if (kind, name) in new and new[(kind, name)] != offset]
    new_offsets = {(kind, offset) for (kind, _), offset in new.items()}
    problems += [f"{kind} {name!r}: id offset {offset} would be gone"
                 for (kind, name), offset in old.items() if (kind, offset) not in new_offsets]
    return problems


def frozen_lines(data) -> str:
    """One line per item and per location, in id order within each kind."""
    lines = []
    for kind, table in (("items", data.ITEM_NAME_TO_ID), ("locations", data.LOCATION_NAME_TO_ID)):
        for name, ap_id in sorted(table.items(), key=lambda pair: pair[1]):
            lines.append(f"{kind}\t{ap_id - data.BASE}\t{name}\n")
    return "".join(lines)


def main():
    data, _ = load_world_tables()
    text = HEADER + frozen_lines(data)
    if OUT.exists():
        problems = moved_ids(OUT.read_text(encoding="utf-8"), text)
        if problems:
            sys.exit(f"{OUT.relative_to(ROOT)} not written: ids would move.\n  " + "\n  ".join(problems))
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
