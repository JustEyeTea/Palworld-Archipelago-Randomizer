"""Writes mod/PalworldArchipelago/Scripts/area_regions.lua: each of the 75 areas (Lock Size: areas) and the region of
the 15 it lies in, so an area can wear its region's wall colour, pass ticket and map stamp. An area belongs to the
region holding its first map row (tools/lock_groups.py); the areas were cut from the regions' rows.
    python3 tools/area_regions.py
Tests: none of its own; the Lua harness loads its file with the mod, and tests/locks_hud.lua checks an area wears its
region's look.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from lock_groups import AREAS, REGIONS  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', 'mod', 'PalworldArchipelago', 'Scripts', 'area_regions.lua')

HEADER = ('-- Generated by tools/area_regions.py from tools/lock_groups.py; do not edit by hand. '
          'Each of the 75 areas\n-- (Lock Size: areas) -> the one of the 15 regions it is in.')


def main():
    region_of_row = {row: region for region, rows in REGIONS.items() for row in rows}
    lines = [HEADER, 'return {']
    missing = []
    for area, rows in AREAS.items():
        region = next((region_of_row[r] for r in rows if r in region_of_row), None)
        if region is None:
            missing.append(area)
            continue
        assert '"' not in area + region and '\\' not in area + region, area
        lines.append(f'    ["{area}"] = "{region}",')
    lines.append('}')
    if missing:
        sys.exit(f'no region for: {", ".join(missing)}')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {OUT}: {len(AREAS)} areas')


if __name__ == '__main__':
    main()
